function realSols = realSols(sols)
    realSols = [];
    for i = 1:size(sols,2)
        sol = sols(:, i);
        if sum(imag(sol).^2)/sum(abs(sol).^2) < 1e-7
            realSols = [realSols, real(sol)];
        end
    end
end



function coeffs = compute_coeffs(data)
    coeffs(1) = 4 * data(1) * data(4);
    coeffs(2) = 4 * data(2) * data(4) + 4 * data(1) * data(5);
    coeffs(3) = 4 * data(2) * data(5);
    coeffs(4) = 4 * data(3) * data(4) + 4 * data(1) * data(6);
    coeffs(5) = 4 * data(3) * data(5) + 4 * data(2) * data(6);
    coeffs(6) = 4 * data(3) * data(6);
    coeffs(7) = -4 * data(1) - 4 * data(4);
    coeffs(8) = -4 * data(2) - 4 * data(5);
    coeffs(9) = -4 * data(3) - 4 * data(6);
    coeffs(10) = 4;
    coeffs(11) = data(1)^2 + data(2)^2 + data(3)^2 - 2 * data(1) * data(4) + data(4)^2 - 2 * data(2) * data(5) + data(5)^2 - 2 * data(3) * data(6) + data(6)^2 - data(7);
    coeffs(12) = 4 * data(8) * data(11);
    coeffs(13) = 4 * data(9) * data(11) + 4 * data(8) * data(12);
    coeffs(14) = 4 * data(9) * data(12);
    coeffs(15) = 4 * data(10) * data(11) + 4 * data(8) * data(13);
