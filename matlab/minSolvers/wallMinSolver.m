    coeffs(18) = -4 * data(8) - 4 * data(11);
    coeffs(19) = -4 * data(9) - 4 * data(12);
    coeffs(20) = -4 * data(10) - 4 * data(13);
    coeffs(21) = data(8)^2 + data(9)^2 + data(10)^2 - 2 * data(8) * data(11) + data(11)^2 - 2 * data(9) * data(12) + data(12)^2 - 2 * data(10) * data(13) + data(13)^2 - data(14);
    coeffs(22) = 4 * data(15) * data(18);
    coeffs(23) = 4 * data(16) * data(18) + 4 * data(15) * data(19);
    coeffs(24) = 4 * data(16) * data(19);
    coeffs(25) = 4 * data(17) * data(18) + 4 * data(15) * data(20);
    coeffs(26) = 4 * data(17) * data(19) + 4 * data(16) * data(20);
    coeffs(27) = 4 * data(17) * data(20);
    coeffs(28) = -4 * data(15) - 4 * data(18);
    coeffs(29) = -4 * data(16) - 4 * data(19);
    coeffs(30) = -4 * data(17) - 4 * data(20);
    coeffs(31) = data(15)^2 + data(16)^2 + data(17)^2 - 2 * data(15) * data(18) + data(18)^2 - 2 * data(16) * data(19) + data(19)^2 - 2 * data(17) * data(20) + data(20)^2 - data(21);
    coeffs(32) = 1;
    coeffs(33) = -1;
end

